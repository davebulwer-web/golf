// Packs the sprite images in assets/dinky, assets/golfers and assets/popups into
// src/dinky-assets.js, src/golfer-assets.js and src/popup-assets.js as data URLs,
// and the trees and ground textures in assets/trees and assets/ground into
// src/tree-assets.js and src/ground-assets.js as raw pixels (they're drawn into
// the hole's picture straight away, before any image could load),
// so the game stays a single file that opens from disk.
// Run with: node tools/pack-assets.mjs (then node tools/build.mjs)

import fs from 'fs';
import zlib from 'zlib';

// Pack every PNG in `dir` (bar the source sheet) as data URLs into src/<file>.
// A folder of folders (one per golfer look) gives names like 'heavy/address'.
function packUrls(dir, file, name, credit) {
  const pngsIn = (d) => fs.readdirSync(d).filter((f) => f.endsWith('.png') && f !== 'source-sheet.png').sort();
  const subs = fs.readdirSync(dir).filter((f) => fs.statSync(`${dir}/${f}`).isDirectory()).sort();
  const pngs = subs.length ? subs.flatMap((s) => pngsIn(`${dir}/${s}`).map((f) => `${s}/${f}`)) : pngsIn(dir);
  const lines = pngs.map((f) => `  '${f.slice(0, -4)}': 'data:image/png;base64,${fs.readFileSync(`${dir}/${f}`).toString('base64')}',`);
  fs.writeFileSync(`src/${file}`, `// Generated by tools/pack-assets.mjs from ${dir}. Do not edit.
${credit}
export const ${name} = {
${lines.join('\n')}
};
`);
  console.log(`src/${file}: ${pngs.length} images, ${Math.round(fs.statSync(`src/${file}`).size / 1024)} KB`);
}

packUrls('assets/dinky', 'dinky-assets.js', 'DINKY_PNGS', '// Art from Dinky Tiny Golf by Mike Moore, www.pixelbitsnbytes.com (see assets/dinky/license.txt).\n');
packUrls('assets/golfers', 'golfer-assets.js', 'GOLFER_PNGS', '// The golfers, cut from Dave\'s sheets by tools/cut-golfer.py.\n');
packUrls('assets/popups', 'popup-assets.js', 'POPUP_PNGS', '// The pop-up pictures, cut from Dave\'s sheet by tools/cut-popups.py.\n');

// Decode an 8-bit RGBA (or RGB) PNG without interlacing: { w, h, rgba }.
function readPng(file) {
  const buf = fs.readFileSync(file);
  let w, h, type, idat = [];
  for (let p = 8; p < buf.length;) {
    const len = buf.readUInt32BE(p), kind = buf.toString('ascii', p + 4, p + 8), data = buf.subarray(p + 8, p + 8 + len);
    if (kind === 'IHDR') {
      w = data.readUInt32BE(0); h = data.readUInt32BE(4); type = data[9];
      if (data[8] !== 8 || (type !== 6 && type !== 2) || data[12] !== 0) throw new Error(`${file}: needs 8-bit RGB(A), not interlaced`);
    }
    if (kind === 'IDAT') idat.push(data);
    p += 12 + len;
  }
  const bpp = type === 6 ? 4 : 3, stride = w * bpp;
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const px = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    for (let x = 0; x < stride; x++) {
      const v = raw[y * (stride + 1) + 1 + x];
      const a = x >= bpp ? px[y * stride + x - bpp] : 0, b = y ? px[(y - 1) * stride + x] : 0, c = x >= bpp && y ? px[(y - 1) * stride + x - bpp] : 0;
      const pa = Math.abs(b - c), pb = Math.abs(a - c), pc = Math.abs(a + b - 2 * c);
      const pred = [0, a, b, (a + b) >> 1, pa <= pb && pa <= pc ? a : pb <= pc ? b : c][f];
      px[y * stride + x] = (v + pred) & 255;
    }
  }
  const rgba = Buffer.alloc(w * h * 4);
  for (let k = 0; k < w * h; k++) {
    for (let i = 0; i < 3; i++) rgba[k * 4 + i] = px[k * bpp + i];
    rgba[k * 4 + 3] = bpp === 4 ? px[k * bpp + 3] : 255;
  }
  return { w, h, rgba };
}

// Pack every PNG in `dir` (bar the source sheet) as raw pixels into src/<file>.
function packPixels(dir, file, name, what) {
  const pngs = fs.readdirSync(dir).filter((f) => f.endsWith('.png') && f !== 'source-sheet.png').sort();
  const lines = pngs.map((f) => {
    const { w, h, rgba } = readPng(`${dir}/${f}`);
    return `  '${f.slice(0, -4)}': [${w}, ${h}, '${rgba.toString('base64')}'],`;
  });
  fs.writeFileSync(`src/${file}`, `// Generated by tools/pack-assets.mjs from ${dir}. Do not edit.
// Each ${what}: [width, height, RGBA pixels in base64].

export const ${name} = {
${lines.join('\n')}
};
`);
  console.log(`src/${file}: ${pngs.length} images, ${Math.round(fs.statSync(`src/${file}`).size / 1024)} KB`);
}

packPixels('assets/trees', 'tree-assets.js', 'TREE_PIXELS', 'tree');
packPixels('assets/ground', 'ground-assets.js', 'GROUND_PIXELS', 'ground texture');
