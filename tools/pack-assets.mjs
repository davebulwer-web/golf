// Packs the sprite images in assets/dinky into src/dinky-assets.js as data URLs,
// so the game stays a single file that opens from disk.
// Run with: node tools/pack-assets.mjs (then node tools/build.mjs)

import fs from 'fs';

const dir = 'assets/dinky';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.png')).sort();
const lines = files.map((f) => `  '${f.slice(0, -4)}': 'data:image/png;base64,${fs.readFileSync(`${dir}/${f}`).toString('base64')}',`);
fs.writeFileSync('src/dinky-assets.js', `// Generated by tools/pack-assets.mjs from assets/dinky. Do not edit.
// Art from Dinky Tiny Golf by Mike Moore, www.pixelbitsnbytes.com (see assets/dinky/license.txt).

export const DINKY_PNGS = {
${lines.join('\n')}
};
`);
console.log(`src/dinky-assets.js: ${files.length} images, ${Math.round(fs.statSync('src/dinky-assets.js').size / 1024)} KB`);
